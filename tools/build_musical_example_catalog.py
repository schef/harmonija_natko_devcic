#!/usr/bin/env python3
"""Build the human-readable index of assigned musical examples.

The catalog is derived only from the reviewed-example location manifest. It
does not promote automated score-region candidates into numbered examples.
"""

import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
LOCATIONS = ROOT / "tools" / "crop-locations.json"
CATALOG_JSON = ROOT / "tools" / "musical-examples.json"
CATALOG_MARKDOWN = ROOT / "tools" / "musical-examples.md"


def example_number(image_path):
    match = re.fullmatch(r"images/[^/]+/primjer-(\d+)-(\d+)(?:-([a-z](?:-[a-z]+)*))?\.png", image_path)
    assert match, f"Unexpected musical-example image path: {image_path}"
    number = f"{int(match.group(1))}.{int(match.group(2))}"
    suffix = match.group(3)
    if not suffix:
        return number
    parts = suffix.split("-")
    if parts[-1] == "nastavak":
        return f"{number} {parts[0]} (nastavak)"
    return f"{number} {'–'.join(parts)}"


def number_key(number):
    match = re.match(r"(\d+)\.(\d+)(?: (.*))?", number)
    assert match, number
    return int(match.group(1)), int(match.group(2)), match.group(3) or ""


def source_location(location):
    if "source_image" in location:
        return {
            "kind": "source_page",
            "source_page": location["source_page"],
            "source_image": location["source_image"],
            "rect": location["rect"],
        }
    assert "rect_on_spread" in location, location
    return {
        "kind": "spread_seam_exception",
        "source_pages": location["source_pages"],
        "rect_on_spread": location["rect_on_spread"],
        "note": location["status_note"],
    }


def catalog_entries(locations):
    entries = []
    for image, location in locations["images"].items():
        number = example_number(image)
        assert (ROOT / image).is_file(), f"Missing cropped image: {image}"
        entry = {
            "name": f"Primjer {number}",
            "number": number,
            "original_printed_pages": location["printed_pages"],
            "original_pdf_spread": location["pdf_page"],
            "location": source_location(location),
            "cropped_image": image,
        }
        if "status_note" in location and "source_image" in location:
            entry["location_note"] = location["status_note"]
        entries.append(entry)
    return sorted(entries, key=lambda entry: number_key(entry["number"]))


def location_summary(entry):
    location = entry["location"]
    if location["kind"] == "source_page":
        return f"`{location['source_page']}` `{location['rect']}`"
    return f"`{' + '.join(location['source_pages'])}` seam `{location['rect_on_spread']}`"


def markdown(entries):
    lines = [
        "# Catalog of currently extracted musical examples",
        "",
        "Generated by `tools/build_musical_example_catalog.py` from `tools/crop-locations.json`. This is not a complete inventory of the book: it lists only examples that have already been assigned a printed number and extracted as crop images. Unassigned automated score-region candidates remain in `tools/score-region-candidates.json`.",
        "",
        "Coordinates are `[left, top, right, bottom]` in 300 dpi source-page pixels. A seam exception intentionally retains its original spread coordinates so that no source content is silently clipped.",
        "",
        "| Example | Original printed page | Source location | Cropped image |",
        "| --- | --- | --- | --- |",
    ]
    for entry in entries:
        pages = ", ".join(str(page) for page in entry["original_printed_pages"])
        lines.append(f"| {entry['name']} | {pages} | {location_summary(entry)} | [{Path(entry['cropped_image']).name}](../{entry['cropped_image']}) |")
    return "\n".join(lines) + "\n"


def main():
    locations = json.loads(LOCATIONS.read_text())
    entries = catalog_entries(locations)
    catalog = {
        "version": 1,
        "description": "Currently extracted and assigned musical examples with their original printed pages, source locations, and cropped image paths. This is not a complete inventory of all musical examples in the book.",
        "source_location_coordinate_system": "[left, top, right, bottom] 300 dpi source-page pixels, except explicit spread_seam_exception entries.",
        "examples": entries,
    }
    CATALOG_JSON.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n")
    CATALOG_MARKDOWN.write_text(markdown(entries))
    print(f"Wrote {len(entries)} assigned musical examples to {CATALOG_JSON} and {CATALOG_MARKDOWN}.")


if __name__ == "__main__":
    main()
