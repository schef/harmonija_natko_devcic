"""M09 individually selected source rectangles; coordinate notes use 2000px display height."""
import json
from pathlib import Path
from PIL import Image

OUT = Path('images/04-neakordicki-b')
OUT.mkdir(parents=True, exist_ok=True)
rows = []
def crop(page, number, box, note='', kind='example', suffix=''):
    source = f'sources/pages/page-{page:03}.png'
    im = Image.open(source)
    factor = im.height / 2000
    rect = [round(v * factor) for v in box]
    name = f'primjer-4-{number}{suffix}' if kind == 'example' else f'zadatak-4-{page}-{number}{suffix}'
    path = OUT / (name + '.png')
    im.crop(tuple(rect)).save(path)
    rows.append(dict(id=name, example=f'4.{number}' if kind == 'example' else str(number), kind=kind,
        printed_page=page, pdf_page=(page+1)//2, source_image=source, rect=rect,
        image=str(path), review_status='pending_independent_review', review_note=note,
        caption=f'Primjer 4.{number}. Izvor: tiskana str. {page}.' if kind=='example' else f'Zadatak {number}. Izvor: tiskana str. {page}.'))

